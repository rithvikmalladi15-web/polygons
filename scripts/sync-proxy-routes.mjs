/**
 * Sync vercel.json rewrites + proxy-routes.ts from embed-proxy-routes.json.
 * Run: npm run proxy:sync
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const routesPath = resolve(root, "src/data/embed-proxy-routes.json");
const routes = JSON.parse(readFileSync(routesPath, "utf8"));

routes.sort((a, b) => b.from.length - a.from.length);

const vercelRewrites = routes.flatMap((r) => {
  const mount = r.to.endsWith("/") ? r.to.slice(0, -1) : r.to;
  const destBase = r.target.replace(/\/$/, "");
  if (r.id === "gd-embed") {
    return [
      { source: `${mount}`, destination: `${destBase}/` },
      { source: `${mount}/:path*`, destination: `${destBase}/:path*` },
    ];
  }
  return [{ source: `${mount}/:path*`, destination: `${destBase}/:path*` }];
});

vercelRewrites.push({
  source: "/((?!api/|_gd/|_abc/|_ext/|assets/|games/|favicon\\.svg).*)",
  destination: "/index.html",
});

const vercelPath = resolve(root, "vercel.json");
const vercel = JSON.parse(readFileSync(vercelPath, "utf8"));
vercel.rewrites = vercelRewrites;
writeFileSync(vercelPath, JSON.stringify(vercel, null, 2) + "\n");

const ts = `/** Auto-generated by scripts/sync-proxy-routes.mjs — edit embed-proxy-routes.json then npm run proxy:sync */
import routes from "../data/embed-proxy-routes.json";

export type EmbedProxyRoute = { id: string; from: string; to: string; target: string };

export const EMBED_PROXY_ROUTES = routes as EmbedProxyRoute[];

export const PROXY_PREFIXES: { from: string; to: string }[] = EMBED_PROXY_ROUTES.map((r) => ({
  from: r.from,
  to: r.to,
})).sort((a, b) => b.from.length - a.from.length);
`;

writeFileSync(resolve(root, "src/lib/proxy-routes.ts"), ts);

console.log(`proxy:sync — ${routes.length} hosts → vercel (${vercelRewrites.length} rewrites)`);
