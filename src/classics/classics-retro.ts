import type { ClassicGame } from "./types";

function abc(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  abcPath: string,
  width = 1280,
  height = 720,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "classic", "retro", "famous"],
    width,
    height,
    shelf: "famous",
    abcPath,
  };
}

function web(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  directUrl: string,
  width = 1024,
  height = 768,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "classic", "retro", "famous", "fnaf"],
    width,
    height,
    shelf: "famous",
    directUrl,
  };
}

function gd(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  gdId: string,
  width = 900,
  height = 600,
  gdPublishSlug?: string,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "classic", "retro", "famous"],
    width,
    height,
    shelf: "famous",
    gdId,
    gdPublishSlug: gdPublishSlug ?? slug,
  };
}

