import type { ClassicGame } from "./types";

/** Famous hits from embeddable hosts (GameDistribution, Nitrome, mirrors). */
function gd(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  gdId: string,
  width = 900,
  height = 600,
  gdPublishSlug?: string,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "famous", "web", "gamedistribution"],
    width,
    height,
    shelf: "famous",
    gdId,
    gdPublishSlug: gdPublishSlug ?? slug,
  };
}

function web(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  directUrl: string,
  width = 900,
  height = 600,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "famous", "web"],
    width,
    height,
    shelf: "famous",
    directUrl,
  };
}

