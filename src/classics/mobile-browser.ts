import type { ClassicGame } from "./types";

/** Famous mobile-style hits playable in the browser (embed mirrors + GD HTML5). */
function gd(
  slug: string,
  name: string,
  line: string,
  tags: string[],
  gdId: string,
  width = 900,
  height = 600,
): ClassicGame {
  return {
    slug,
    name,
    line,
    tags: [...tags, "mobile", "browser"],
    width,
    height,
    shelf: "famous",
    gdId,
  };
}

